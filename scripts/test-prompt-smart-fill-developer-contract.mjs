import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const smart = fs.readFileSync(path.join(root,'public/prompt-library-smart-fill.mts'),'utf8');
const palette = fs.readFileSync(path.join(root,'public/prompt-library-command-palette.mts'),'utf8');
const hints = fs.readFileSync(path.join(root,'public/prompt-library-smart-fill-hints.mts'),'utf8');
assert.match(smart,/HafizePromptLibrarySmartFill/);
assert.match(smart,/extractVariables/);
assert.match(smart,/replaceVariables/);
assert.match(palette,/PromptLibraryCommandPalette/);
assert.match(palette,/HafizePromptLibrarySmartFill/);
assert.match(hints,/HafizePromptSmartFillHints/);
assert.doesNotMatch(hints,/loadItems/);
assert.doesNotMatch(hints,/saveItems/);
assert.doesNotMatch(palette,/saveItems/);
console.log('prompt smart-fill developer boundaries: ok');
