import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { assertNumericLimit } from './source-contract.mjs';
const root = new URL('../', import.meta.url);
const core = await readFile(new URL('public/typed/legacy/prompt-library-smart-insert.ts', root), 'utf8');
const center = await readFile(new URL('public/typed/legacy/prompt-library-smart-insert-center.ts', root), 'utf8');
const history = await readFile(new URL('public/typed/legacy/prompt-library-smart-insert-history.ts', root), 'utf8');
const presets = await readFile(new URL('public/typed/legacy/prompt-library-smart-insert-presets.ts', root), 'utf8');
const activity = await readFile(new URL('public/typed/legacy/prompt-library-smart-insert-activity.ts', root), 'utf8');
assert.match(core, /maxBody\s*:\s*8000/); assert.match(core, /maxVariables\s*:\s*12/); assert.match(core, /maxVariableValue\s*:\s*1000/);
assertNumericLimit(center, 'MAX_PROFILES', 24); assertNumericLimit(center, 'MAX_PROFILE_NAME', 60); assertNumericLimit(center, 'MAX_VARIABLES', 12); assertNumericLimit(center, 'MAX_VALUE', 1000);
assertNumericLimit(history, 'MAX_ENTRIES', 40); assertNumericLimit(history, 'MAX_ID', 120); assertNumericLimit(history, 'MAX_LABEL', 100);
assertNumericLimit(presets, 'MAX_PRESETS', 32); assertNumericLimit(presets, 'MAX_VALUES', 12); assertNumericLimit(presets, 'MAX_VALUE', 1000);
assertNumericLimit(activity, 'MAX_DAYS', 14); assertNumericLimit(activity, 'MAX_ROWS', 7);
assert.doesNotMatch(center, /\.slice\(0,\s*9999999\)/); assert.doesNotMatch(history, /\.slice\(0,\s*9999999\)/);
console.log('prompt-library-smart-insert-bounds: ok');
