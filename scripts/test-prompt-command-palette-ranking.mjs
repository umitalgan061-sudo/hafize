import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const text = fs.readFileSync(path.join(process.cwd(), 'public/prompt-library-command-palette.ts'), 'utf8');
assert.match(text, /title === q/);
assert.match(text, /title\.startsWith\(q\)/);
assert.match(text, /title\.includes\(q\)/);
assert.match(text, /tags\.includes\(q\)/);
assert.match(text, /body\.includes\(q\)/);
assert.match(text, /return 100/);
assert.match(text, /return 80/);
assert.match(text, /return 60/);
assert.match(text, /return 45/);
assert.match(text, /return 20/);
assert.match(text, /MAX_RESULTS/);
console.log('prompt command palette ranking: ok');
