import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(new URL('../', import.meta.url).pathname);
const read = (path) => readFile(resolve(root, path), 'utf8');
const sources = {};
for (const name of ['prompt-library-smart-insert','prompt-library-smart-insert-center','prompt-library-smart-insert-history','prompt-library-smart-insert-presets']) sources[name] = await read('public/typed/legacy/' + name + '.ts');
const source = Object.values(sources).join('\n');
assert(source.includes('hafize.prompt-library.variable-profiles.v1'));
assert(source.includes('hafize.prompt-library.smart-insert-history.v1'));
assert(source.includes('hafize.prompt-library.variable-presets.v1'));
assert(source.includes('center-state'));
assert(!source.match(/localStorage\.clear\s*\(/));
assert(!source.match(/sessionStorage\.clear\s*\(/));
assert(!source.match(/removeItem\([^)]*variable-profiles/));
assert(!source.match(/removeItem\([^)]*smart-insert-history/));
assert(!source.match(/removeItem\([^)]*variable-presets/));
const docs = await read('docs/TYPESCRIPT_SMART_INSERT_MIGRATION.md');
assert.match(docs, /storage anahtar/);
assert.match(docs, /veri migration/i);
console.log('Smart Insert storage compatibility: OK');
