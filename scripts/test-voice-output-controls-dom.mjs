import assert from 'node:assert/strict';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const voiceOutput = require('../public/voice-output.js');

class FakeClassList {
  toggle() {}
}

class FakeNode {
  constructor(tagName = 'div') {
    this.tagName = tagName.toUpperCase();
    this.id = '';
    this.type = '';
    this.className = '';
    this.value = '';
    this.textContent = '';
    this.hidden = false;
    this.disabled = false;
    this.parentNode = null;
    this.children = [];
    this.attributes = new Map();
    this.listeners = new Map();
    this.classList = new FakeClassList();
  }
  setAttribute(name, value) { this.attributes.set(name, String(value)); }
  addEventListener(type, callback) { this.listeners.set(type, callback); }
  removeEventListener(type) { this.listeners.delete(type); }
  append(...nodes) {
    for (const node of nodes) {
      if (!node) continue;
      node.parentNode = this;
      this.children.push(node);
    }
  }
  insertAdjacentElement(position, node) {
    if (position !== 'afterend' || !this.parentNode) return null;
    const siblings = this.parentNode.children;
    const index = siblings.indexOf(this);
    node.parentNode = this.parentNode;
    siblings.splice(index + 1, 0, node);
    return node;
  }
  remove() {
    if (!this.parentNode) return;
    const siblings = this.parentNode.children;
    const index = siblings.indexOf(this);
    if (index >= 0) siblings.splice(index, 1);
    this.parentNode = null;
  }
}

const card = new FakeNode('section');
const toggle = new FakeNode('button');
toggle.id = 'voiceOutputToggle';
card.append(toggle);
const input = new FakeNode('textarea');
const messages = new FakeNode('div');
messages.querySelectorAll = () => [];

const documentRef = {
  hidden: false,
  querySelector(selector) {
    if (selector === '#voiceOutputToggle') return toggle;
    if (selector === '.voice-card') return card;
    if (selector === '#messageInput') return input;
    if (selector === '#messages') return messages;
    return null;
  },
  createElement(tagName) { return new FakeNode(tagName); },
  addEventListener() {},
  removeEventListener() {}
};

class Utterance {
  constructor(text) { this.text = text; }
}
const root = {
  speechSynthesis: {
    speak() {},
    cancel() {},
    pause() {},
    resume() {},
    getVoices() { return []; }
  },
  SpeechSynthesisUtterance: Utterance,
  localStorage: { getItem() { return 'true'; }, setItem() {} }
};

const controller = voiceOutput.installVoiceOutput(documentRef, root);
assert.ok(controller);

const directIds = card.children.map((node) => node.id).filter(Boolean);
assert.deepEqual(directIds, [
  'voiceOutputToggle',
  'voicePauseToggle',
  'voiceOutputStatus',
  'voiceRateWrap',
  'voicePlaybackActions'
], 'browser install should create the complete playback control surface beside the existing toggle');

const pause = card.children.find((node) => node.id === 'voicePauseToggle');
const status = card.children.find((node) => node.id === 'voiceOutputStatus');
const rateWrap = card.children.find((node) => node.id === 'voiceRateWrap');
const actions = card.children.find((node) => node.id === 'voicePlaybackActions');

assert.equal(pause.type, 'button');
assert.equal(pause.hidden, true);
assert.equal(status.attributes.get('role'), 'status');
assert.equal(status.attributes.get('aria-live'), 'polite');
assert.equal(rateWrap.tagName, 'LABEL');
assert.equal(rateWrap.children.at(-1).id, 'voiceRateSelect');
assert.equal(rateWrap.children.at(-1).children.length, 4, 'bounded rate selector exposes exactly four options');
assert.deepEqual(actions.children.map((node) => node.id), ['voiceReplayButton', 'voiceStopButton']);
assert.equal(actions.children[0].attributes.get('aria-label'), 'Son Hafize yanıtını tekrar oku');
assert.equal(actions.children[1].attributes.get('aria-label'), 'Sesli yanıtı durdur');

controller.destroy();
assert.deepEqual(card.children.map((node) => node.id), ['voiceOutputToggle'], 'destroy removes only controls generated by voice-output');
assert.equal(toggle.listeners.has('click'), false, 'destroy detaches the existing voice toggle listener');

console.log('voice output generated playback DOM lifecycle tests passed');
