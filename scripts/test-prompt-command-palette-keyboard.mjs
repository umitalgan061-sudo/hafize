import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const text = fs.readFileSync(path.join(process.cwd(), 'public/prompt-library-command-palette.ts'), 'utf8');
assert.match(text, /event\.ctrlKey \|\| event\.metaKey/);
assert.match(text, /event\.shiftKey/);
assert.match(text, /event\.key\.toLowerCase\(\) !== 'o'/);
assert.match(text, /ArrowDown/);
assert.match(text, /ArrowUp/);
assert.match(text, /event\.key === 'Enter'/);
assert.match(text, /event\.key === 'Escape'/);
assert.match(text, /preventDefault\(\)/);
console.log('prompt command palette keyboard: ok');
