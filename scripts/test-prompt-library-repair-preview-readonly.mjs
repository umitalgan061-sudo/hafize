import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const source=await fs.readFile('public/prompt-library-safety.js','utf8');
const start=source.indexOf('function buildRepairPreview');
assert.ok(start>=0,'buildRepairPreview exists');
const end=source.indexOf('\n  function ', start + 1);
assert.ok(end>start,'buildRepairPreview body is delimited');
const body=source.slice(start,end);
assert.match(body,/buildSafeRepair\(storage\)/,'the preview reuses the repair plan');
assert.doesNotMatch(body,/setItem/,'the preview never writes to storage');
assert.doesNotMatch(body,/saveItems/,'the preview never saves prompts');
assert.doesNotMatch(body,/removeItem/,'the preview never clears storage');
console.log('prompt-library-repair-preview-readonly: ok');
